// Bundles the browser UI into the Go package that embeds it.
//
// The built file is committed: `go build` and `go test` on the service must not
// need Node. Run `node build.mjs --check` to prove the committed bundle still
// matches its sources; `make ui` and CI use that mode.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const outfile = resolve(here, '../internal/api/ui/app.js');
const banner = '// Generated by ui/build.mjs from ui/src. Do not edit by hand.\n';

const result = await build({
  entryPoints: [resolve(here, 'src/main.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  target: ['es2022'],
  platform: 'browser',
  charset: 'utf8',
  legalComments: 'none',
  minify: false,
  sourcemap: false,
  banner: { js: banner.trimEnd() },
  write: false,
});

const output = result.outputFiles?.[0];
if (!output) {
  console.error('esbuild produced no output');
  process.exit(1);
}
const next = output.text;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(outfile, 'utf8');
  } catch {
    console.error(`${outfile} is missing; run aube run build`);
    process.exit(1);
  }
  if (current !== next) {
    console.error(`${outfile} is out of date; run aube run build`);
    process.exit(1);
  }
  console.log(`${outfile} is up to date (${next.length} bytes)`);
} else {
  writeFileSync(outfile, next);
  console.log(`wrote ${outfile} (${next.length} bytes)`);
}